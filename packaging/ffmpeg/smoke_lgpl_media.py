@record("10-bit AV1 (yuv420p10le) with BT.2020/HLG tags in MKV")
def check_av1_10bit(work: Path):
    from av.video.reformatter import ColorPrimaries, ColorRange, ColorTrc

    color = {
        "color_primaries": int(ColorPrimaries.BT2020),
        "color_trc": int(ColorTrc.ARIB_STD_B67),
        "colorspace": 9,  # AVCOL_SPC_BT2020_NCL
        "color_range": int(ColorRange.MPEG),
    }
    result = round_trip(
        work,
        "av1-10bit-hlg.mkv",
        container_format="matroska",
        codec="libsvtav1",
        pix_fmt="yuv420p10le",
        options={"crf": "35", "preset": "8"},
        color=color,
        expect="libdav1d",
        decode_fmt="yuv420p10le",
    )
    with av.open(str(work / "av1-10bit-hlg.mkv")) as container:
        context = container.streams.video[0].codec_context
        stream_color = {
            "color_primaries": int(context.color_primaries),
            "color_trc": int(context.color_trc),
            "colorspace": int(context.colorspace),
            "color_range": int(context.color_range),
        }
    if result["last_color"] != color:
        raise AssertionError(f"decoded frame color tags {result['last_color']} != {color}")
    result["stream_color"] = stream_color
    return result


