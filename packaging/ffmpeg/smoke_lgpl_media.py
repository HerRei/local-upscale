#!/usr/bin/env python3
"""Functional smoke test for the LGPL-only PyAV build.

Run inside the test environment that has the built wheel, numpy and pillow installed::

    build/lgpl-media/testenv/bin/python packaging/ffmpeg/smoke_lgpl_media.py \
        [--ffmpeg /opt/homebrew/bin/ffmpeg] [--work-dir DIR] [--report report.json]

Required checks (exit status 1 if any fails): royalty-free encode/decode round trips,
absent patent-encumbered codecs, a bwdif filter graph and the audio resampler.

Exploratory checks (reported, never fatal): stream-copy of AAC (and H.264) from
fixtures generated by a user-installed ``ffmpeg`` binary -- used only to create test
inputs, never linked -- and how PyAV exposes streams whose decoder is absent.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
import traceback
from fractions import Fraction
from pathlib import Path

import av
import numpy as np

WIDTH, HEIGHT, FRAMES, RATE = 320, 240, 30, 30
AUDIO_RATE = 48000

RESULTS: list[dict] = []


def record(name: str, required: bool = True):
    """Decorator: run a check, record pass/fail with details or the exception."""

    def wrap(function):
        def run(*args, **kwargs):
            entry = {"name": name, "required": required}
            try:
                details = function(*args, **kwargs)
                entry.update(passed=True, details=details)
            except Exception as exc:  # noqa: BLE001 - every failure must be reported
                entry.update(
                    passed=False,
                    error=f"{type(exc).__name__}: {exc}",
                    traceback=traceback.format_exc(limit=4),
                )
            RESULTS.append(entry)
            status = "PASS" if entry["passed"] else ("FAIL" if required else "INFO-FAIL")
            print(f"[{status}] {name}", flush=True)
            if not entry["passed"]:
                print(f"    {entry['error']}", flush=True)
            return entry

        return run

    return wrap


def rgb_frame(index: int) -> np.ndarray:
    y, x = np.mgrid[0:HEIGHT, 0:WIDTH]
    image = np.empty((HEIGHT, WIDTH, 3), dtype=np.uint8)
    image[..., 0] = (x + index * 8) % 256
    image[..., 1] = (y + index * 4) % 256
    image[..., 2] = ((x + y) // 2 + index * 16) % 256
    return image


def audio_chunk(start: int, samples: int) -> np.ndarray:
    t = (np.arange(start, start + samples) / AUDIO_RATE).astype(np.float64)
    left = 0.3 * np.sin(2 * np.pi * 440 * t)
    right = 0.3 * np.sin(2 * np.pi * 660 * t)
    interleaved = np.empty(2 * samples, dtype=np.int16)
    interleaved[0::2] = (left * 32767).astype(np.int16)
    interleaved[1::2] = (right * 32767).astype(np.int16)
    return interleaved.reshape(1, -1)


def encode(
    path: Path,
    container_format: str,
    codec: str,
    pix_fmt: str,
    options: dict[str, str] | None = None,
    color: dict[str, int] | None = None,
    with_opus: bool = False,
) -> dict:
    with av.open(str(path), "w", format=container_format) as output:
        video = output.add_stream(codec, rate=RATE, options=options or {})
        video.width, video.height, video.pix_fmt = WIDTH, HEIGHT, pix_fmt
        video.time_base = Fraction(1, RATE)
        if color:
            for key, value in color.items():
                setattr(video.codec_context, key, value)
        audio = None
        if with_opus:
            audio = output.add_stream("libopus", rate=AUDIO_RATE, layout="stereo")
            audio.format = "s16"
        for index in range(FRAMES):
            frame = av.VideoFrame.from_ndarray(rgb_frame(index), format="rgb24")
            if color:
                frame = frame.reformat(
                    format=pix_fmt, dst_colorspace=av.video.reformatter.Colorspace.BT2020
                )
                for key, value in color.items():
                    setattr(frame, key, value)
            frame.pts = index
            frame.time_base = Fraction(1, RATE)
            for packet in video.encode(frame):
                output.mux(packet)
        for packet in video.encode(None):
            output.mux(packet)
        if audio is not None:
            # One second of audio in 1024-sample chunks (PyAV re-chunks to 960 for Opus).
            position = 0
            while position < AUDIO_RATE:
                frame = av.AudioFrame.from_ndarray(
                    audio_chunk(position, 1024), format="s16", layout="stereo"
                )
                frame.sample_rate = AUDIO_RATE
                frame.pts = position
                frame.time_base = Fraction(1, AUDIO_RATE)
                position += 1024
                for packet in audio.encode(frame):
                    output.mux(packet)
            for packet in audio.encode(None):
                output.mux(packet)
    return {"bytes": path.stat().st_size}


def decode_check(path: Path, expect_codec: str, pix_fmt: str | None = None) -> dict:
    with av.open(str(path)) as container:
        stream = container.streams.video[0]
        codec_name = stream.codec_context.name
        frames = 0
        last_pts = None
        formats = set()
        color = None
        for frame in container.decode(video=0):
            if frame.width != WIDTH or frame.height != HEIGHT:
                raise AssertionError(f"frame {frames} is {frame.width}x{frame.height}")
            if frame.pts is None or (last_pts is not None and frame.pts <= last_pts):
                raise AssertionError(f"pts not increasing: {last_pts} -> {frame.pts}")
            last_pts = frame.pts
            formats.add(frame.format.name)
            color = {
                "color_primaries": int(frame.color_primaries),
                "color_trc": int(frame.color_trc),
                "colorspace": int(frame.colorspace),
                "color_range": int(frame.color_range),
            }
            frames += 1
        audio_info = None
        if container.streams.audio:
            container.seek(0)
            samples = 0
            last = None
            for frame in container.decode(audio=0):
                if last is not None and frame.pts <= last:
                    raise AssertionError(f"audio pts not increasing: {last} -> {frame.pts}")
                last = frame.pts
                samples += frame.samples
            audio_stream = container.streams.audio[0]
            audio_info = {
                "codec": audio_stream.codec_context.name,
                "rate": audio_stream.codec_context.sample_rate,
                "channels": audio_stream.codec_context.channels,
                "decoded_samples": samples,
            }
            if audio_info["rate"] != AUDIO_RATE or audio_info["channels"] != 2 or samples < 40000:
                raise AssertionError(f"unexpected audio decode result {audio_info}")
    if codec_name != expect_codec:
        raise AssertionError(f"decoder {codec_name!r}, expected {expect_codec!r}")
    if frames != FRAMES:
        raise AssertionError(f"decoded {frames} frames, expected {FRAMES}")
    if pix_fmt and formats != {pix_fmt}:
        raise AssertionError(f"decoded formats {formats}, expected {pix_fmt}")
    return {
        "decoder": codec_name,
        "stream_codec_expected": expect_codec,
        "frames": frames,
        "formats": sorted(formats),
        "last_color": color,
        "audio": audio_info,
    }


def round_trip(work: Path, name: str, **kwargs) -> dict:
    path = work / name
    expect = kwargs.pop("expect")
    decode_fmt = kwargs.pop("decode_fmt", None)
    encoded = encode(path, **kwargs)
    return {"file": path.name, **encoded, **decode_check(path, expect, decode_fmt)}


def stream_description(stream) -> dict:
    """Everything PyAV exposes about a stream, tolerating absent decoders."""
    info: dict[str, object] = {
        "repr": repr(stream),
        "class": type(stream).__name__,
        "type": stream.type,
        "index": stream.index,
        "codec_context_is_none": stream.codec_context is None,
        "time_base": str(stream.time_base),
        "duration": stream.duration,
        "frames": stream.frames,
        "metadata": dict(stream.metadata),
    }
    for attribute in ("name", "codec", "codec_tag", "profile", "width", "height", "sample_rate"):
        try:
            value = getattr(stream, attribute)
            info[attribute] = value if isinstance(value, (str, int, type(None))) else repr(value)
        except Exception as exc:  # noqa: BLE001
            info[attribute] = f"raises {type(exc).__name__}: {exc}"
    if stream.codec_context is not None:
        info["codec_context_name"] = stream.codec_context.name
    return info


