@record("patent-encumbered codecs are absent")
def check_absent_codecs():
    outcomes = {}
    for name, mode in (
        ("libx264", "w"),
        ("h264", "r"),
        ("aac", "w"),
        ("aac", "r"),
        ("hevc", "r"),
    ):
        try:
            av.codec.Codec(name, mode)
        except Exception as exc:  # noqa: BLE001
            outcomes[f"{name}/{mode}"] = f"raises {type(exc).__name__}: {exc}"
        else:
            outcomes[f"{name}/{mode}"] = "AVAILABLE"
    present = [key for key, value in outcomes.items() if value == "AVAILABLE"]
    if present:
        raise AssertionError(f"codecs unexpectedly available: {present}")
    return outcomes


@record("bwdif filter graph")
def check_bwdif():
    graph = av.filter.Graph()
    source = graph.add_buffer(
        width=WIDTH, height=HEIGHT, format="yuv420p", time_base=Fraction(1, RATE)
    )
    bwdif = graph.add("bwdif", "mode=send_field:parity=tff:deint=all")
    sink = graph.add("buffersink")
    source.link_to(bwdif)
    bwdif.link_to(sink)
    graph.configure()
    produced = []
    for index in range(6):
        frame = av.VideoFrame.from_ndarray(rgb_frame(index), format="rgb24").reformat(
            format="yuv420p"
        )
        frame.pts = index
        frame.time_base = Fraction(1, RATE)
        graph.push(frame)
        while True:
            try:
                produced.append(graph.pull())
            except (av.BlockingIOError, av.EOFError):
                break
    graph.push(None)
    while True:
        try:
            produced.append(graph.pull())
        except (av.BlockingIOError, av.EOFError):
            break
    if len(produced) < 6:
        raise AssertionError(f"bwdif send_field produced only {len(produced)} frames")
    return {
        "input_frames": 6,
        "output_frames": len(produced),
        "size": [produced[0].width, produced[0].height],
    }


@record("AudioResampler")
def check_resampler():
    resampler = av.AudioResampler(format="fltp", layout="mono", rate=16000)
    frame = av.AudioFrame.from_ndarray(audio_chunk(0, 4800), format="s16", layout="stereo")
    frame.sample_rate = AUDIO_RATE
    frame.pts = 0
    frame.time_base = Fraction(1, AUDIO_RATE)
    out = resampler.resample(frame) + resampler.resample(None)
    samples = sum(item.samples for item in out)
    if not 1500 <= samples <= 1700:
        raise AssertionError(f"resampled {samples} samples, expected about 1600")
    return {
        "frames": len(out),
        "samples": samples,
        "format": out[0].format.name,
        "layout": out[0].layout.name,
        "rate": out[0].sample_rate,
    }


def make_fixtures(ffmpeg: str, work: Path) -> dict[str, Path]:
    fixtures = {
        "aac_only.mp4": [
            "-f",
            "lavfi",
            "-i",
            "sine=frequency=440:sample_rate=48000:duration=2",
            "-c:a",
            "aac",
            "-b:a",
            "128k",
        ],
        "h264_aac.mp4": [
            "-f",
            "lavfi",
            "-i",
            f"testsrc2=size={WIDTH}x{HEIGHT}:rate={RATE}:duration=1",
            "-f",
            "lavfi",
            "-i",
            "sine=frequency=440:sample_rate=48000:duration=1",
            "-c:v",
            "libx264",
            "-pix_fmt",
            "yuv420p",
            "-c:a",
            "aac",
            "-shortest",
        ],
        "hevc_aac.mkv": [
            "-f",
            "lavfi",
            "-i",
            f"testsrc2=size={WIDTH}x{HEIGHT}:rate={RATE}:duration=1",
            "-f",
            "lavfi",
            "-i",
            "sine=frequency=440:sample_rate=48000:duration=1",
            "-c:v",
            "libx265",
            "-pix_fmt",
            "yuv420p",
            "-c:a",
            "aac",
            "-shortest",
        ],
    }
    made = {}
    for name, arguments in fixtures.items():
        target = work / name
        result = subprocess.run(
            [ffmpeg, "-hide_banner", "-loglevel", "error", "-y", *arguments, str(target)],
            capture_output=True,
            text=True,
        )
        if result.returncode == 0:
            made[name] = target
        else:
            print(f"    fixture {name} not generated: {result.stderr.strip()[-300:]}")
    return made


def remux(
    source: Path,
    target: Path,
    container_format: str,
    stream_types: set[str],
    opaque: bool | None = None,
) -> dict:
    with av.open(str(source)) as input_container:
        with av.open(str(target), "w", format=container_format) as output:
            mapping = {}
            for stream in input_container.streams:
                if stream.type in stream_types:
                    mapping[stream.index] = output.add_stream_from_template(stream, opaque=opaque)
            packets = 0
            for packet in input_container.demux(*[input_container.streams[i] for i in mapping]):
                if packet.dts is None:
                    continue  # demuxer flush packet
                packet.stream = mapping[packet.stream.index]
                output.mux(packet)
                packets += 1
    with av.open(str(target)) as check:
        streams = [stream_description(stream) for stream in check.streams]
        read_back = sum(1 for packet in check.demux() if packet.dts is not None)
    if packets == 0 or read_back != packets:
        raise AssertionError(f"muxed {packets} packets but read back {read_back}")
    return {
        "target": target.name,
        "muxed_packets": packets,
        "read_back_packets": read_back,
        "bytes": target.stat().st_size,
        "output_streams": streams,
    }


def mux_stream_copy(ffmpeg: str, source: Path, target: Path, container_format: str) -> dict:
    """Copy the AAC track with ``add_mux_stream('aac')`` (no codec context).

    PyAV cannot name the codec of a decoder-less stream, so the caller must already know
    it is AAC. The result is validated with the user's ffprobe/ffmpeg (fixture tools).
    """
    with av.open(str(source)) as input_container:
        with av.open(str(target), "w", format=container_format) as output:
            template = input_container.streams.audio[0]
            stream = output.add_mux_stream("aac", rate=AUDIO_RATE)
            stream.time_base = template.time_base
            packets = 0
            for packet in input_container.demux(template):
                if packet.dts is None:
                    continue
                packet.stream = stream
                output.mux(packet)
                packets += 1
    ffprobe = str(Path(ffmpeg).with_name("ffprobe"))
    probe = subprocess.run(
        [ffprobe, "-v", "error", "-show_entries", "stream=codec_name,channels,extradata_size"]
        + ["-of", "compact", str(target)],
        capture_output=True,
        text=True,
    )
    decode = subprocess.run(
        [ffmpeg, "-v", "error", "-i", str(target), "-f", "null", "-"],
        capture_output=True,
        text=True,
    )
    details = {
        "muxed_packets": packets,
        "ffprobe": (probe.stdout + probe.stderr).strip()[-400:],
        "ffmpeg_decode_errors": decode.stderr.strip()[-400:],
    }
    if decode.returncode != 0 or decode.stderr.strip():
        raise AssertionError(f"copied AAC track is not decodable by ffmpeg: {details}")
    return details


def exploratory_checks(ffmpeg: str | None, work: Path) -> None:
    if (work / "av1-opus.mp4").exists():
        for opaque in (None, True):

            @record(
                "control: stream copy AV1+Opus (decoders present) mp4 -> matroska "
                f"(add_stream_from_template, opaque={opaque})",
                required=False,
            )
            def control(opaque=opaque):
                return remux(
                    work / "av1-opus.mp4",
                    work / f"copy-av1-opus-opaque-{opaque}.mkv",
                    "matroska",
                    {"audio", "video"},
                    opaque=opaque,
                )

            control()
    if not ffmpeg:
        RESULTS.append(
            {
                "name": "AAC stream copy",
                "required": False,
                "passed": False,
                "error": "skipped: no ffmpeg binary available to generate AAC fixtures",
            }
        )
        return
    fixtures = make_fixtures(ffmpeg, work)

    @record("inspect absent-decoder streams (AAC/H.264/HEVC inputs)", required=False)
    def inspect():
        report = {}
        for name, path in fixtures.items():
            with av.open(str(path)) as container:
                entry = {
                    "container_format": container.format.name,
                    "streams": [stream_description(s) for s in container.streams],
                }
                decode_attempts = {}
                for stream in container.streams:
                    try:
                        next(iter(container.decode(stream)), None)
                        decode_attempts[f"#{stream.index}"] = "decode OK"
                    except Exception as exc:  # noqa: BLE001
                        decode_attempts[f"#{stream.index}"] = (
                            f"raises {type(exc).__module__}.{type(exc).__name__}: {exc}"
                        )
                    container.seek(0)
                entry["decode_attempts"] = decode_attempts
                report[name] = entry
        return report

    inspect()
    for source_name, types, formats in (
        ("aac_only.mp4", {"audio"}, ("mp4", "matroska")),
        ("h264_aac.mp4", {"audio"}, ("mp4", "matroska")),
        ("h264_aac.mp4", {"audio", "video"}, ("mp4", "matroska")),
        ("hevc_aac.mkv", {"audio", "video"}, ("mp4", "matroska")),
    ):
        if source_name not in fixtures:
            continue
        for container_format in formats:
            suffix = "mp4" if container_format == "mp4" else "mkv"
            label = "+".join(sorted(types))
            target = work / f"copy-{Path(source_name).stem}-{label}.{suffix}"

            @record(
                f"stream copy {label} from {source_name} -> {container_format} "
                "(add_stream_from_template)",
                required=False,
            )
            def copy(source=fixtures[source_name], target=target, fmt=container_format, t=types):
                return remux(source, target, fmt, t)

            copy()
    if "aac_only.mp4" in fixtures:
        for container_format in ("mp4", "matroska"):
            suffix = "mp4" if container_format == "mp4" else "mkv"
            target = work / f"muxcopy-aac.{suffix}"

            @record(
                f"stream copy audio from aac_only.mp4 -> {container_format} "
                "(add_mux_stream('aac'), no codec context)",
                required=False,
            )
            def mux_copy(target=target, fmt=container_format):
                return mux_stream_copy(ffmpeg, fixtures["aac_only.mp4"], target, fmt)

            mux_copy()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ffmpeg", default=shutil.which("ffmpeg"), help="Fixture generator")
    parser.add_argument("--work-dir", type=Path, help="Keep outputs here (default: temp dir)")
    parser.add_argument("--report", type=Path, help="Write the JSON report here")
    args = parser.parse_args()
    temporary = None
    if args.work_dir:
        work = args.work_dir.resolve()
        work.mkdir(parents=True, exist_ok=True)
    else:
        temporary = tempfile.TemporaryDirectory(prefix="lgpl-media-smoke-")
        work = Path(temporary.name)
    print(f"PyAV {av.__version__} from {av.__file__}")
    print(f"FFmpeg {av.ffmpeg_version_info}; libavcodec {av.library_versions['libavcodec']}")
    try:
        check_av1_mp4(work)
        check_av1_mkv(work)
        check_vp9_webm(work)
        check_vp9_mp4(work)
        check_ffv1_mkv(work)
        check_av1_10bit(work)
        check_opus_av1_mp4(work)
        check_absent_codecs()
        check_bwdif()
        check_resampler()
        exploratory_checks(args.ffmpeg, work)
    finally:
        report = {
            "av_version": av.__version__,
            "ffmpeg_version": av.ffmpeg_version_info,
            "fixture_ffmpeg": args.ffmpeg,
            "results": RESULTS,
            "required_passed": all(r["passed"] for r in RESULTS if r["required"]),
        }
        text = json.dumps(report, indent=2, default=str)
        if args.report:
            args.report.write_text(text + "\n")
        if temporary is not None:
            temporary.cleanup()
    print(text)
