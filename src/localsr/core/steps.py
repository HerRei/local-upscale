@dataclass(frozen=True)
class StepParameter:
    """Typed parameter definition and bounds for a pipeline step."""

    name: str
    kind: str  # "bool", "int", "number", "choice", "int_choice", or "str"
    default: bool | int | float | str | None = None
    minimum: int | float | None = None
    maximum: int | float | None = None
    choices: tuple[str, ...] = ()
    int_choices: tuple[int, ...] = ()
    ui_minimum: int | float | None = None
    ui_maximum: int | float | None = None
    ui_default: int | float | None = None
    nullable: bool = False


@dataclass(frozen=True)
class StepDefinition:
    """Metadata for one LocalSR pipeline step or fix stage."""

    id: str
    media: tuple[str, ...]
    phase: str
    order: int
    needs_model: bool
    stage_kind: str | None = None
    role: str | None = None
    fix_kind: str | None = None
    is_fix_stage: bool = False
    fix_chip_order: int | None = None
    in_image_pipeline: bool = False
    in_recipe_stages: bool = False
    label: str = ""
    row_label: str = ""
    short_name: str = ""
    stage_label: str = ""
    required_feature: str | None = None
    parameters: tuple[StepParameter, ...] = ()


@dataclass(frozen=True)
class StepLimits:
    """Hard bounds derived from the step registry and preserved for compatibility."""

    max_fix_stages: int
    max_fix_chips: int
