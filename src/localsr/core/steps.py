"""Single source of truth for LocalSR pipeline steps, ordering, limits and parameters.

Non-Python targets (the Rust desktop host and Svelte webview) consume
``desktop/src-tauri/resources/steps.json`` generated by
``scripts/export_desktop_steps.py``.
"""

