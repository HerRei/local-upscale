class _ASPPModuleDeformable(nn.Module):
    def __init__(self, in_channels, planes, kernel_size, padding):
        super(_ASPPModuleDeformable, self).__init__()
        self.atrous_conv = DeformableConv2d(
            in_channels, planes, kernel_size=kernel_size, stride=1, padding=padding, bias=False
        )
        self.bn = nn.BatchNorm2d(planes)
        self.relu = nn.ReLU(inplace=True)

    def forward(self, x):
        x = self.atrous_conv(x)
        x = self.bn(x)
        return self.relu(x)


class ASPPDeformable(nn.Module):
    def __init__(self, in_channels, out_channels=None, parallel_block_sizes=None):
        if parallel_block_sizes is None:
            parallel_block_sizes = [1, 3, 7]
        super(ASPPDeformable, self).__init__()
        self.down_scale = 1
        if out_channels is None:
            out_channels = in_channels
        self.in_channelster = 256 // self.down_scale
        self.aspp1 = _ASPPModuleDeformable(in_channels, self.in_channelster, 1, padding=0)
        self.aspp_deforms = nn.ModuleList(
            [
                _ASPPModuleDeformable(
                    in_channels, self.in_channelster, conv_size, padding=int(conv_size // 2)
                )
                for conv_size in parallel_block_sizes
            ]
        )
        self.global_avg_pool = nn.Sequential(
            nn.AdaptiveAvgPool2d((1, 1)),
            nn.Conv2d(in_channels, self.in_channelster, 1, stride=1, bias=False),
            nn.BatchNorm2d(self.in_channelster),
            nn.ReLU(inplace=True),
        )
        self.conv1 = nn.Conv2d(
            self.in_channelster * (2 + len(self.aspp_deforms)), out_channels, 1, bias=False
        )
        self.bn1 = nn.BatchNorm2d(out_channels)
        self.relu = nn.ReLU(inplace=True)
        self.dropout = nn.Dropout(0.5)

    def forward(self, x):
        # The 1x1 projection is linear; summing its slices avoids holding all
        # deformable branches and their concatenation in accelerator memory.
        width = self.in_channelster
        result = F.conv2d(self.aspp1(x), self.conv1.weight[:, :width])
        for index, branch in enumerate(self.aspp_deforms, start=1):
            if x.device.type == "mps":
                torch.mps.synchronize()
                torch.mps.empty_cache()
            projected = F.conv2d(
                branch(x), self.conv1.weight[:, index * width : (index + 1) * width]
            )
            result = result + projected
        pooled = F.interpolate(
            self.global_avg_pool(x), size=x.shape[-2:], mode="bilinear", align_corners=True
        )
        result = result + F.conv2d(pooled, self.conv1.weight[:, -width:])
        return self.dropout(self.relu(self.bn1(result)))
